// Writes `system-map/src/extract/python/stdlib.rs`: the union of `sys.stdlib_module_names` over CPython 3.10 to 3.15,
// read from `Python/stdlib_module_names.h` at each tag (spec #589, "Resolution of an absolute import"). Run it by hand
// from the repository root when a new CPython minor version ships, with `node scripts/system-map/python-stdlib.mjs`: it
// fetches from GitHub, so CI never runs it. CI tests the checked-in constant instead (`system-map/tests/python.rs`).

import { writeFileSync } from "node:fs";

const TAGS = ["v3.10.0", "v3.11.0", "v3.12.0", "v3.13.0", "v3.14.0", "v3.15.0"];
const OUT = new URL("../../system-map/src/extract/python/stdlib.rs", import.meta.url);

/** The names a tag's header lists, which holds one string literal per name. */
async function namesAt(tag) {
	const url = `https://raw.githubusercontent.com/python/cpython/${tag}/Python/stdlib_module_names.h`;
	const response = await fetch(url);
	if (!response.ok) {
		throw new Error(`${url}: ${response.status}`);
	}
	const names = [...(await response.text()).matchAll(/^\s*"([^"]+)",/gm)].map((m) => m[1]);
	if (names.length < 200) {
		throw new Error(`${url}: only ${names.length} names; has the header's format changed?`);
	}
	return names;
}

const union = new Set();
for (const tag of TAGS) {
	for (const name of await namesAt(tag)) {
		union.add(name);
	}
}
const names = [...union].sort();

const text = `//! The standard library's module names, as a provider in the first-segment lookup (spec #589, "Resolution of an
//! absolute import"). Generated by \`scripts/system-map/python-stdlib.mjs\`; do not edit it by hand.

/// The union of \`sys.stdlib_module_names\` over CPython 3.10 to 3.15, read from \`Python/stdlib_module_names.h\` at the
/// tags ${TAGS.join(", ")}.
/// It is sorted, and holds the built-in and frozen names too, and names a later version dropped, such as \`distutils\`
/// and \`imp\`.
#[rustfmt::skip]
const NAMES: [&str; ${names.length}] = [
${names.map((n) => `    "${n}",`).join("\n")}
];

/// Whether \`name\` is a top-level standard-library module of any of those versions.
pub(super) fn contains(name: &str) -> bool {
    NAMES.binary_search(&name).is_ok()
}
`;
writeFileSync(OUT, text);
console.log(`${names.length} names from ${TAGS.join(", ")}`);
